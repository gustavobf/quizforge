import { resolve } from 'node:path'
import { expect, test } from '@playwright/test'

test('complete workflow against the real backend', async ({ page }, testInfo) => {
  test.skip(!process.env.QUIZFORGE_E2E_LIVE, 'Requires isolated backend on port 8082')
  test.setTimeout(90_000)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  const email = `browser-${testInfo.project.name}-${Date.now()}@example.test`
  await page.goto('/register')
  await page.getByRole('textbox', { name: 'Nome', exact: true }).fill('Browser Validation')
  await page.getByRole('textbox', { name: 'E-mail' }).fill(email)
  await page.getByLabel(/^Senha/).fill('Validation123!')
  await page.getByRole('button', { name: 'Criar conta', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Novo simulado' })).toBeVisible()

  await page.goto('/subjects')
  await page.getByRole('button', { name: 'Nova matéria', exact: true }).click()
  await page.getByRole('textbox', { name: 'Nome', exact: true }).fill('Java de validacao')
  await page.getByRole('textbox', { name: 'Descrição' }).fill('Perguntas da validacao integrada')
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Java de validacao' })).toBeVisible()

  await page.goto('/questions')
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Planilha modelo' }).click()
  expect((await downloadEvent).suggestedFilename()).toBe('quizforge-perguntas.xlsx')
  await page.getByRole('combobox', { name: 'Matéria' }).click()
  await page.getByRole('option', { name: 'Java de validacao' }).click()
  await page
    .locator('input[type="file"]')
    .setInputFiles(resolve('../quizforge-srv/target/validation-questions.xlsx'))
  await page.getByRole('button', { name: 'Importar perguntas', exact: true }).click()
  await expect(page.getByText('3 perguntas importadas.')).toBeVisible()

  await page.goto('/')
  await page.getByRole('textbox', { name: 'Nome do simulado' }).fill('Revisão integrada')
  await page.getByRole('spinbutton', { name: 'Quantidade de perguntas' }).fill('3')
  await page.getByRole('button', { name: 'Iniciar simulado' }).click()
  await expect(page).toHaveURL(/\/exam\/\d+$/)
  await expect(page.getByRole('button', { name: 'Finalizar', exact: true })).toBeInViewport()
  await page.getByRole('radio', { name: /Correct/ }).click()
  await page.getByRole('button', { name: 'Ir para pergunta 2, em branco', exact: true }).click()
  await page.getByRole('radio', { name: /Wrong/ }).click()
  await page.reload()
  await expect(page.getByRole('radio', { name: /Wrong/ })).toBeChecked()
  await page.getByRole('button', { name: 'Finalizar', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('2 respondidas e 1 em branco')
  await page.getByRole('button', { name: 'Confirmar finalização' }).click()
  await expect(page).toHaveURL(/\/history\/\d+$/)
  await expect(page.getByRole('article')).toHaveCount(3)
  await page.reload()
  await expect(page.getByRole('article')).toHaveCount(3)
  await page.getByRole('button', { name: 'Certas', exact: true }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  await page.getByRole('button', { name: 'Erradas', exact: true }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  await page.getByRole('button', { name: 'Em branco', exact: true }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  await page.getByRole('button', { name: 'Todas', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('live-results.png'), fullPage: true })
  expect(
    await page.evaluate(
      () => document.documentElement.scrollWidth <= document.documentElement.clientWidth,
    ),
  ).toBe(true)

  const token = await page.evaluate(() => localStorage.getItem('accessToken'))
  const api = process.env.QUIZFORGE_E2E_API || 'http://localhost:8082'
  const headers = { Authorization: `Bearer ${token}` }
  const before = await (await page.request.get(`${api}/history/summary`, { headers })).json()
  expect(before.totalExams).toBe(1)
  expect(before.totalQuestionsAnswered).toBe(2)
  await page.goto('/')
  await page.getByRole('textbox', { name: 'Nome do simulado' }).fill('Tentativa cancelada')
  await page.getByRole('spinbutton', { name: 'Quantidade de perguntas' }).fill('3')
  await page.getByRole('button', { name: 'Iniciar simulado' }).click()
  await expect(page).toHaveURL(/\/exam\/\d+$/)
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await page.getByRole('button', { name: 'Cancelar simulado', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
  const after = await (await page.request.get(`${api}/history/summary`, { headers })).json()
  expect(after).toEqual(before)
  await page.goto('/history')
  await expect(page.getByRole('row')).toHaveCount(2)
  await page.goto('/dashboard')
  await expect(page.getByRole('table', { name: 'Desempenho por matéria' })).toBeVisible()
  await expect(page.getByRole('cell', { name: '1 / 3', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('live-dashboard.png'), fullPage: true })

  await page.goto('/profile')
  await page.getByRole('textbox', { name: 'Nome', exact: true }).fill('Updated Validation')
  await page.getByRole('button', { name: 'Salvar alterações' }).click()
  await expect(page.getByText('Perfil atualizado.')).toBeVisible()
  await page.getByLabel(/^Senha atual/).fill('Validation123!')
  await page.getByLabel(/^Nova senha/).fill('Updated123!')
  await page.getByLabel(/^Confirmar nova senha/).fill('Updated123!')
  await page.getByRole('button', { name: 'Alterar senha', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByText('Senha alterada. Entre novamente com sua nova senha.')).toBeVisible()
  await page.getByRole('textbox', { name: 'E-mail' }).fill(email)
  await page.getByLabel(/^Senha/).fill('Updated123!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Novo simulado' })).toBeVisible()
  await page.goto('/profile')
  await page.getByRole('button', { name: 'Excluir minha conta' }).click()
  await page.getByRole('button', { name: 'Excluir conta', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  expect(errors).toEqual([])
})
